void TestCmdCipherKeySwitch() {
    dyna::CmdCipher c;
    const uint8_t init_cmd[] = {
        0x0f, 0xf0, 0xe0, 0x20, 0x00, 0x00, 0x00, 0x00, 0x23, 0x8d, 0xc0, 0xd0, 0x0e, 0xd0, 0x38, 0x75,
        0xe8, 0x38, 0xdf, 0xeb, 0x33, 0x7d, 0x39, 0x52, 0xe3, 0x78, 0xeb, 0xd1, 0xb7, 0x84, 0xef, 0x65,
        0x00, 0x9a,
    };
    std::array<uint8_t, 132> enc_init{};
    assert(c.EncryptCommand(init_cmd, sizeof(init_cmd), enc_init));
    assert(enc_init[0] == 0x0f && enc_init[1] == 0xf0);

    const uint8_t fw_cmd[] = {0x1f, 0xf0, 0x9f, 0x04, 0x00, 0x00, 0x00, 0x00};
    std::array<uint8_t, 132> enc_fw{};
    assert(c.EncryptCommand(fw_cmd, sizeof(fw_cmd), enc_fw));

    dyna::AesBlock blk;
    blk.SetKey128(init_cmd + 16);
    uint8_t dec[128]{};
    for (size_t off = 0; off < 128; off += 16) {
        blk.DecryptBlock(enc_fw.data() + 2 + off, dec + off);
    }
    assert(std::memcmp(dec, fw_cmd + 2, 6) == 0);
}

void TestXORCipherRoundTrip() {
    dyna::XORCipher x;
    x.SetKey(dyna::kSessionXORKey.data(), dyna::kSessionXORKey.size());

    std::vector<uint8_t> orig(188, 0);
    orig[0] = 0x47;
    orig[1] = 0x21; // priority=1, PID=0x0100
    orig[2] = 0x00;
    orig[3] = 0x80; // scrambling=2
    for (size_t i = 4; i < 188; ++i) orig[i] = uint8_t(i * 7);

    auto pkt = orig;
    x.Crypt(pkt.data() + 4, pkt.data() + 4, 128);
    x.DecryptPacket(pkt.data(), pkt.size());
    assert((pkt[1] & 0x20) == 0);
    assert(std::memcmp(pkt.data() + 4, orig.data() + 4, 184) == 0);
}

void TestSettler() {
    dyna::Settler s(3, 100);
    std::vector<uint8_t> pkts(188 * 4, 0);
    // pkt 0: PAT (PID 0, CC 0)
    pkts[0] = 0x47; pkts[1] = 0x00; pkts[2] = 0x00; pkts[3] = 0x10;
    // pkt 1: PID 0x100, CC 0
    pkts[188] = 0x47; pkts[189] = 0x01; pkts[190] = 0x00; pkts[191] = 0x10;
    // pkt 2: PID 0x100, CC 1
    pkts[376] = 0x47; pkts[377] = 0x01; pkts[378] = 0x00; pkts[379] = 0x11;
    // pkt 3: PID 0x100, CC 2
    pkts[564] = 0x47; pkts[565] = 0x01; pkts[566] = 0x00; pkts[567] = 0x12;

    auto out = s.Feed(pkts.data(), pkts.size());
    assert(s.Settled());
    assert(!s.GaveUp());
    assert(out.size() == pkts.size());
}

